##Power Iteration Method
##Dated: 21/10/2026
import numpy as np
A = np.array([[2, 1],[1,2]])
b = np.array([1, 2])
prev_eigval=0
tol = 0.000000001
for i in range(1000):
  y = A@b
  b = y / np.linalg.norm(y)
  eigval = (b.T @ A@ b)
  if np.abs(eigval - prev_eigval)<tol:
    print(f"Finally Converged at iteration {i}!")
    break
  prev_eigval = eigval
print("Eigenvector:",b)
print("Eigvalue:",eigval)