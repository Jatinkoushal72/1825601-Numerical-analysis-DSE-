##Inverse Power Method
##Dated: 21/10/2026
import numpy as np
A = np.array([[2, 1],[1,2]])
b = np.array([1, 2])

A_inverse = np.linalg.inv(A)
c = np.array([-1,10])
prev_eigval=-10.0
tol = 0.0000000000001
i=100
for i in range(1000):
  c = A_inverse @ c
  c = c / np.linalg.norm(c)
  eigval = (c.T @ A_inverse @ c)
  if np.abs(eigval - prev_eigval)<tol:
    print(f"Finally Converged at iteration {i}!")
    break
  prev_eigval = eigval
print("Eigenvector:",c)
print("Eigvalue:",eigval)